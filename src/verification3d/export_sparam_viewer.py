"""
export_sparam_viewer.py
=======================
Write viewer/data_sparam.js for viewer/viewer_sparam.html (the interactive
S-parameter / impedance-painting demo, theory/01 and 01b).

viewer_sparam.html loads `window.KSF_SPARAM` with:

  nT          number of tetrahedra
  texW        side of the square GPU texture holding one texel per tet
              (smallest integer with texW*texW >= nT)
  verts       flat list, 12 floats per tet (its 4 vertex positions)
  neighbors   per tet, the 4 face-adjacent tet ids (-1 on the boundary)
  materials   per tet, the initial material id (0 = air everywhere)
  mat_names   material names, in the order of the ids used by the shader
  impedances  name -> port impedance Z; MUST match imp() in the viewer's
              simulation shader (air 1, metal 0.01, wood 0.3, water 0.5)

The mesh is the project's Kuhn cube (src/ksf3d/mesh3d_uniform.py), centred on
the origin like the other viewer exporters. This file carries geometry and
connectivity only; the propagation itself is the viewer's own illustrative
GPU update (see theory/01, theory/01b and sparam_wave_verify.py for the
verified engine).

Run:  python3 src/verification3d/export_sparam_viewer.py   # -> viewer/data_sparam.js
"""
import os, sys, json
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
import numpy as np
from ksf3d.mesh3d_uniform import kuhn_cube

MAT_NAMES = ["air", "metal", "wood", "water"]
IMPEDANCES = {"air": 1.0, "metal": 0.01, "wood": 0.3, "water": 0.5}


def face_neighbors(T):
    """For each tet, the ids of the tets sharing each of its 4 faces (-1 = boundary)."""
    owner = {}
    nb = -np.ones((len(T), 4), dtype=int)
    for t, tet in enumerate(T):
        for f in range(4):
            face = tuple(sorted(int(v) for k, v in enumerate(tet) if k != f))
            if face in owner:
                s, g = owner.pop(face)
                nb[t, f] = s
                nb[s, g] = t
            else:
                owner[face] = (t, f)
    return nb


def build(n=8):
    V, T = kuhn_cube(n)
    V = V - 0.5                                  # centre on the origin
    nb = face_neighbors(T)
    # every interior face is shared by exactly two tets; the rest are boundary
    assert np.all((nb == -1).sum() == 2 * 6 * n * n), "unexpected boundary face count"
    nT = len(T)
    texW = int(np.ceil(np.sqrt(nT)))
    verts = [round(float(c), 6) for tet in T for vi in tet for c in V[vi]]
    return {
        "nT": nT,
        "texW": texW,
        "verts": verts,
        "neighbors": nb.tolist(),
        "materials": [0] * nT,
        "mat_names": MAT_NAMES,
        "impedances": IMPEDANCES,
    }


def main():
    d = build(5)                                 # 750 tets: viewer assumes nT <= 1024
    out = os.path.join(os.path.dirname(__file__), "..", "..", "viewer", "data_sparam.js")
    out = os.path.abspath(out)
    with open(out, "w") as f:
        f.write("// Auto-generated by src/verification3d/export_sparam_viewer.py\n")
        f.write("// Kuhn-cube tetrahedra + face adjacency for viewer_sparam.html.\n")
        f.write("window.KSF_SPARAM = ")
        json.dump(d, f, separators=(",", ":"))
        f.write(";\n")
    print(f"wrote {out}  (nT={d['nT']}, texW={d['texW']}, "
          f"{os.path.getsize(out)/1024:.0f} KB)")


if __name__ == "__main__":
    main()
